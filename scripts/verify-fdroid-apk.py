#!/usr/bin/env python3
"""Fails if an APK ships Google code that must never reach an F-Droid build.

Deliberately narrow. `verify-fdroid-dependencies.py` is the gate that decides whether a Google
dependency may ship at all: it checks resolved artifact coordinates, which is the unit a licence
attaches to, and both CI jobs run it before this one. What is left for an APK scan is the two
things a coordinate check structurally cannot see:

  - Code that arrives without a coordinate of its own. A shaded or bundled artifact carries
    classes under package names unrelated to the coordinate that delivered them.
  - Anything a Gradle plugin generates rather than a dependency supplying. The google-services
    plugin injecting its keys into the fdroid variant was a real leak on this branch, and no
    dependency list would ever have shown it.

An earlier version of this script also kept an allowlist of permitted `com.google.*` package
roots. That is gone. A dex descriptor carries no package/class boundary, so it could only match
the first segment after `com.google` and had to approve roots as broad as `api`, which made it
impossible to verify by inspection and caught nothing the coordinate check does not catch
earlier and better.

R8 renames and merges classes, and inlines their code into other classes. The dex of such an APK
no longer names most of the packages it was built from, so the dex alone proves nothing. The R8
mapping still names every class and every inlined or merged method by its original name. An APK
which R8 produced is therefore only accepted together with its mapping: R8 writes the same ID
into the dex and into the mapping, and the scan refuses a mapping of another build.

Usage:  verify-fdroid-apk.py [--mapping <mapping.txt>]... <apk> [<apk> ...]

Exit codes: 0 clean, 1 an APK carries Google code, 2 an APK could not be verified.
"""

import argparse
import collections
import json
import re
import sys
import zipfile

# Matched at any depth, so re-admitting one of these takes more than widening a list somewhere.
DENIED_PACKAGES = (
    "com.google.android.gms",
    "com.google.android.play",
    "com.google.firebase",
    "com.google.mlkit",
    "com.google.ar.core",
)

# Class references appear in dex as type descriptors, hence the leading `L`.
DENIED_DESCRIPTORS = tuple((package, ("L" + package.replace(".", "/")).encode()) for package in DENIED_PACKAGES)

# In a mapping, original names are written with dots. The package must start a name and must end
# at a package boundary: `com.google.android.playful` is not `com.google.android.play`.
DENIED_MAPPING_NAMES = tuple(
    (package, re.compile(r"(?<![\w.$])" + re.escape(package) + r"(?=[.\s:(,)\[\]]|$)")) for package in DENIED_PACKAGES
)

# Generated by the google-services plugin. Harmless strings on their own, but their presence
# means the plugin reached a variant it has no business in.
GOOGLE_SERVICES_RESOURCES = (b"google_app_id", b"google_api_key", b"gcm_defaultSenderId")

# R8 leaves a marker in every dex file it writes. The marker of a build with a mapping carries
# the ID of that mapping.
R8_MARKER = re.compile(rb'~~R8(\{[^{}]*\})')
MAP_ID_MARKER_KEY = "pg-map-id"
MAP_ID_HEADER = re.compile(r"^#\s*pg_map_id:\s*(\S+)\s*$")
# The ID is in the header of the mapping. A later comment line must not be able to supply it.
MAX_MAPPING_HEADER_LINES = 64


class UnverifiableError(Exception):
    """The scan cannot tell whether the APK is clean. Never to be reported as clean or as dirty."""


def r8_map_ids(dex: bytes) -> set[str]:
    """The mapping IDs of the R8 markers in a dex file. Empty for a dex which R8 did not minify."""
    ids = set()
    for match in R8_MARKER.finditer(dex):
        try:
            marker = json.loads(match.group(1))
        except ValueError:
            continue
        map_id = marker.get(MAP_ID_MARKER_KEY) if isinstance(marker, dict) else None
        if isinstance(map_id, str) and map_id:
            ids.add(map_id)
    return ids


def read_mapping(path: str) -> tuple[str, collections.Counter[str]]:
    """Returns the ID of a mapping and how often it names each denied package."""
    map_id = None
    denied: collections.Counter[str] = collections.Counter()
    with open(path, encoding="utf-8", errors="replace") as mapping:
        for number, line in enumerate(mapping):
            if map_id is None and number < MAX_MAPPING_HEADER_LINES and line.startswith("#"):
                if header := MAP_ID_HEADER.match(line):
                    map_id = header.group(1)
                    continue
            if "com.google." not in line:
                continue
            for package, pattern in DENIED_MAPPING_NAMES:
                denied[package] += len(pattern.findall(line))
    if map_id is None:
        raise UnverifiableError(f"{path} has no pg_map_id header, so it cannot be matched to an APK")
    return map_id, +denied


def check(path: str, mappings: dict[str, collections.Counter[str]] | None = None) -> list[str]:
    """Returns a list of problems, empty when the APK is clean.

    `mappings` holds the denied package counts of every given mapping, by mapping ID.
    """
    mappings = mappings or {}
    problems = []
    with zipfile.ZipFile(path) as z:
        denied: collections.Counter[str] = collections.Counter()
        map_ids: set[str] = set()
        for entry in z.namelist():
            if not entry.endswith(".dex"):
                continue
            dex = z.read(entry)
            map_ids |= r8_map_ids(dex)
            for package, descriptor in DENIED_DESCRIPTORS:
                if (count := dex.count(descriptor)) > 0:
                    denied[package] += count

        for package, count in sorted(denied.items()):
            problems.append(f"{package} ({count} class references)")

        missing = sorted(map_ids - mappings.keys())
        if missing:
            raise UnverifiableError(
                "R8 produced this APK, so its dex does not name the code it was built from. "
                f"Pass the mapping of this build with --mapping (pg_map_id {', '.join(missing)})"
            )
        if mappings and not map_ids:
            raise UnverifiableError(
                "a mapping was given, but the dex carries no R8 marker to match it against"
            )
        for map_id in sorted(map_ids):
            for package, count in sorted(mappings[map_id].items()):
                problems.append(f"{package} ({count} references in the R8 mapping)")

        try:
            arsc = z.read("resources.arsc")
        except KeyError:
            arsc = b""
        for marker in GOOGLE_SERVICES_RESOURCES:
            if marker in arsc:
                problems.append(f"the {marker.decode()} resource from the google-services plugin")

    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="verify-fdroid-apk.py", description=__doc__.splitlines()[0])
    parser.add_argument(
        "--mapping",
        action="append",
        default=[],
        metavar="<mapping.txt>",
        help="R8 mapping of the build; required for an APK which R8 produced",
    )
    parser.add_argument("apks", nargs="*", metavar="<apk>")
    args = parser.parse_args(argv[1:])
    if not args.apks:
        parser.print_usage(sys.stderr)
        return 2

    mappings: dict[str, collections.Counter[str]] = {}
    for mapping in args.mapping:
        try:
            map_id, denied = read_mapping(mapping)
        except (OSError, UnverifiableError) as error:
            print(f"::error file={mapping}::cannot use the mapping: {error}", file=sys.stderr)
            return 2
        mappings[map_id] = denied

    failed = False
    for apk in args.apks:
        name = apk.rsplit("/", 1)[-1]
        # An unreadable path must not look like a rejection. A glob that matched nothing
        # reaches here as its own literal pattern, and exiting 1 on that would read as
        # "the APK is dirty" when the truth is "there is no APK".
        try:
            problems = check(apk, mappings)
        except (OSError, zipfile.BadZipFile) as error:
            print(f"::error file={apk}::cannot read {name}: {error}", file=sys.stderr)
            return 2
        except UnverifiableError as error:
            print(f"::error file={apk}::cannot verify {name}: {error}", file=sys.stderr)
            return 2
        if problems:
            failed = True
            for problem in problems:
                # ::error:: is picked up as an annotation when this runs in GitHub Actions.
                print(f"::error file={apk}::{name} carries {problem}")
        else:
            print(f"clean: {name}")

    if failed:
        print(
            "\nAn APK carries Google code that cannot ship on F-Droid. If it came from a "
            "dependency, verify-fdroid-dependencies.py should have caught it first and the "
            "mismatch is worth understanding; if not, something is generating or bundling it "
            "into the build.",
            file=sys.stderr,
        )
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
